"""mcq.json -> data.js (window.MCQ). usage: python3 build_data.py mcq.json ../data.js"""
import json, re, sys
d = json.load(open(sys.argv[1]))
# PDF typo: C16's third incorrect answer is labelled "E." instead of "C."
for q in d['C']:
    if q['id'] == 'C16' and 'C' not in q['why']:
        b, c = re.split(r'\s*E\. Source: ANY, Destination: ANY, Protocol: TCP, Port: 80, Allow\s*', q['why']['B'])
        q['why']['B'], q['why']['C'] = b, c
bad = [q['id'] for e in d for q in d[e] if set(q['why']) | set(q['answer']) != set(q['options'])]
assert not bad, bad
assert all(len(d[e]) == 85 for e in d)
open(sys.argv[2], 'w').write('// Generated by tools/build_data.py from the PDF. Do not edit by hand.\nwindow.MCQ = ' + json.dumps(d, ensure_ascii=False) + ';\n')
print('ok', sum(len(v) for v in d.values()))
